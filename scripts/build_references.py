"""Generate SDK, CLI and HTTP references without instantiating clients or running commands.

Run with the repository's frozen base environment. Only --help is invoked; no
agent/evaluator calls, app lifespan, database, credential or dataset access occurs.
"""

from __future__ import annotations

import argparse
import dataclasses
import inspect
import json
from pathlib import Path
from typing import Any
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]


def page(title: str, description: str, body: str) -> str:
    return (
        f"---\ntitle: {json.dumps(title)}\ndescription: {json.dumps(description)}\n---\n\n"
        "{/* Generated by scripts/build_references.py; do not edit this reference independently. */}\n\n"
        + body.rstrip()
        + "\n"
    )


def code(value: str, language: str = "python") -> str:
    return f"```{language}\n{value}\n```\n"


def prose(value: str) -> str:
    return value.replace("<", "&lt;").replace("{", "&#123;").replace("}", "&#125;")


def signature(name: str, obj: Any, *, method: bool = False) -> str:
    sig = inspect.signature(obj)
    if inspect.isclass(obj):
        sig = sig.replace(return_annotation=inspect.Signature.empty)
    if method:
        sig = sig.replace(parameters=[p for key, p in sig.parameters.items() if key not in ("self", "cls")])
    prefix = "async " if inspect.iscoroutinefunction(inspect.unwrap(obj)) else ""
    return f"{prefix}{name}{sig}"


def symbol(name: str, obj: Any) -> str:
    sections = [f"## {name}\n", code(signature(name, obj))]
    # Only the symbol's own documentation, not inherited BaseModel/Protocol internals.
    doc = inspect.cleandoc(obj.__doc__ or "")
    if doc:
        sections.append(prose(doc) + "\n")
    if inspect.isclass(obj):
        for key, value in obj.__dict__.items():
            if key.startswith("_"):
                continue
            if isinstance(value, property):
                sections += [f"### {name}.{key}\n", code(signature(key, value.fget, method=True))]
            elif inspect.isfunction(value) or isinstance(value, staticmethod):
                function = value.__func__ if isinstance(value, staticmethod) else value
                sections += [f"### {name}.{key}\n", code(signature(key, function, method=True))]
                if function.__doc__:
                    sections.append(prose(inspect.cleandoc(function.__doc__)) + "\n")
    return "\n".join(sections)


def sdk_files() -> dict[str, str]:
    from pydantic import BaseModel
    from pydantic.json_schema import models_json_schema

    from everybench import evaluation, sdk

    if Path(sdk.__file__).resolve() != ROOT / "src/everybench/sdk.py":
        raise RuntimeError("Install this checkout with uv sync --frozen before generating references.")
    names = [name for name in evaluation.__all__ if hasattr(sdk, name)]
    tracing = (
        "Import from `everybench.sdk`. These signatures and docstrings come from the public implementation; "
        "no tracing client is constructed during generation. Context-manager methods are used with `with`.\n\n"
        "For lifecycle, instrumentation and privacy examples, read the [tracing guide](/guides/tracing-sdk).\n\n"
        + symbol("EveryBench", sdk.EveryBench)
        + "\n## Health\n\nReturned by `health`, `flush` and `close`.\n\n"
        + code("\n".join(f"{f.name}: {f.type}" for f in dataclasses.fields(sdk.Health)))
        + "\n"
        + code(signature("Health.to_dict", sdk.Health.to_dict, method=True))
    )
    functions, models, protocols = [], [], []
    for name in names:
        obj = getattr(sdk, name)
        if inspect.isclass(obj) and issubclass(obj, BaseModel):
            models.append((name, obj))
        elif inspect.isclass(obj) and getattr(obj, "_is_protocol", False):
            protocols.append((name, obj))
        else:
            functions.append((name, obj))
    evaluation_body = (
        "Import these public functions and adapters from `everybench.sdk`. Signatures are extracted "
        "without constructing adapters, loading datasets or calling providers. Annotations are shown as declared.\n\n"
        "`evaluate_sync(*args, **kwargs)` forwards the same arguments to `evaluate`; it is not for use "
        "inside an active event loop. There are no instance `EveryBench.evaluate()` methods.\n\n"
        "Read the [evaluation workflow and examples](/guides/evaluation-sdk) and "
        "[contracts and consent requirements](/guides/evaluate) alongside this reference.\n\n"
        + "\n".join(symbol(name, obj) for name, obj in functions)
    )
    types_body = (
        "Public data contracts and protocols imported from `everybench.sdk`. Field requirements, defaults "
        "and constraints below come from Pydantic. "
        "[Download the complete model JSON Schema](/reference/sdk-models.json).\n\n"
        "Do not pass `BenchmarkCase` to the agent: the agent receives `AgentInput`, which excludes references/rubrics. "
        "Read [the evaluation guide](/guides/evaluation-sdk) for worked implementations.\n\n"
    )
    for name, model in models:
        types_body += f"## {name}\n\n"
        for field_name, field in model.model_fields.items():
            annotation = inspect.formatannotation(field.annotation)
            default = (
                "required"
                if field.is_required()
                else f"factory: {field.default_factory.__name__}"
                if field.default_factory
                else repr(field.default)
            )
            types_body += code(f"{field_name}: {annotation}  # {default}") + "\n"
            if field.metadata:
                types_body += "Constraints: " + " · ".join(f"`{item!r}`" for item in field.metadata) + ".\n\n"
        for key, member in model.__dict__.items():
            if isinstance(member, property) and not key.startswith("_"):
                types_body += code(signature(f"{name}.{key}", member.fget, method=True)) + "\n"
    for name, protocol in protocols:
        types_body += symbol(name, protocol) + "\n"
        if annotations := getattr(protocol, "__annotations__", {}):
            types_body += code("\n".join(f"{k}: {v}" for k, v in annotations.items())) + "\n"
    _, model_schema = models_json_schema([(model, "validation") for _, model in models], title="EveryBench SDK models")
    return {
        "sdk-evaluation.mdx": page(
            "Python evaluation API",
            "Generated evaluation functions, targets and trace-source signatures.",
            evaluation_body,
        ),
        "sdk-tracing.mdx": page(
            "Python tracing API", "Generated EveryBench client methods, defaults and delivery health fields.", tracing
        ),
        "sdk-types.mdx": page(
            "Python types and protocols",
            "Generated evaluation data fields, constraints and extension protocols.",
            types_body,
        ),
        "sdk-models.json": json.dumps(model_schema, sort_keys=True, indent=2) + "\n",
    }


def cli_commands():
    import click
    from typer.main import get_command

    from everybench.cli import app

    command = get_command(app)

    def walk(current, path, parent=None):
        context = click.Context(current, info_name=path[-1] if path else "everybench", parent=parent)
        yield path, current
        # Typer can vendor its Click classes; use the group protocol rather
        # than isinstance against a separately installed click.Group.
        if callable(getattr(current, "list_commands", None)):
            for name in sorted(current.list_commands(context)):
                child = current.get_command(context, name)
                if child is not None and not child.hidden:
                    yield from walk(child, (*path, name), context)

    return command, list(walk(command, ()))


def cli_file() -> str:
    from click.testing import CliRunner
    from typer import rich_utils

    _, commands = cli_commands()
    runner = CliRunner()
    body = (
        "Every supported command and subgroup below is discovered from the Typer/Click command tree. "
        "Each block is captured from that exact command's `--help`, not executed business logic.\n\n"
        "For examples, JSON-output interpretation, consent and command-specific exit behavior, "
        "read [Using the CLI](/guides/cli). This reference describes the checked-out code; "
        "your installed version's `everybench COMMAND --help` remains authoritative.\n\n"
    )
    for path, _ in commands:
        name = "everybench" + (" " + " ".join(path) if path else "")
        body += f"- [`{name}`](#{name.replace(' ', '-')})\n"
    for path, command in commands:
        name = "everybench" + (" " + " ".join(path) if path else "")
        # Invoke only this command's eager help option; traversing root with
        # subcommand arguments could execute a future parent-group callback.
        # Rich reads some settings at import time (including GITHUB_ACTIONS).
        # Pin presentation locally so CI and developer terminals agree.
        with patch.multiple(rich_utils, MAX_WIDTH=100, COLOR_SYSTEM=None, FORCE_TERMINAL=False):
            result = runner.invoke(
                command,
                ["--help"],
                prog_name=name,
                color=False,
                terminal_width=100,
                max_content_width=100,
                env={"COLUMNS": "100", "TERM": "dumb", "NO_COLOR": "1", "FORCE_COLOR": "0"},
            )
        if result.exit_code != 0 or result.exception:
            raise RuntimeError(f"Help generation failed for {name}; no command was run.") from result.exception
        text = "\n".join(line.rstrip() for line in result.output.splitlines()).strip()
        body += f"\n## {name}\n\n" + code(text, "text")
    return page(
        "CLI command reference", "Generated help for every supported command, argument, flag and default.", body
    )


def http_files() -> dict[str, str]:
    from everybench.server import create_app

    # Deliberately do not enter lifespan or call a route: no DB or worker starts.
    spec = create_app(workers=0).openapi()
    body = (
        "Generated from `create_app(workers=0).openapi()` without starting the app, workers or database. "
        "[Download the OpenAPI schema](/reference/openapi.json).\n\n"
        "Read [HTTP authorization and usage](/guides/http-api) and [operator configuration](/guides/operators). "
        "The documentation host is not your execution API. No live API playground is enabled here. "
        "Authentication still applies when an endpoint's OpenAPI operation does not declare a security scheme. "
        "Flexible response dictionaries are not stronger typed guarantees; use the installed server's schema.\n\n"
        "OTLP payload formats and producer sealing are documented in the "
        "[tracing guide](/guides/typescript-tracing), not fully described by generic request objects in OpenAPI.\n\n"
    )
    for path, operations in sorted(spec["paths"].items()):
        for method, operation in sorted(operations.items()):
            if method not in {"get", "post", "put", "patch", "delete", "head", "options"}:
                continue
            body += f"## {method.upper()} {prose(path)}\n\n"
            body += prose(operation.get("summary", "")) + "\n\n"
            if operation.get("description"):
                body += prose(operation["description"]) + "\n\n"
            details = {key: operation[key] for key in ("parameters", "requestBody", "responses") if key in operation}
            body += code(json.dumps(details, sort_keys=True, indent=2), "json") + "\n"
    return {
        "http.mdx": page(
            "HTTP endpoint reference", "Generated methods, request parameters, bodies and responses from OpenAPI.", body
        ),
        "openapi.json": json.dumps(spec, sort_keys=True, indent=2) + "\n",
    }


def render_files() -> dict[str, str]:
    return {**sdk_files(), "cli.mdx": cli_file(), **http_files()}


def build(*, check: bool = False) -> list[str]:
    directory = ROOT / "docs-site/reference"
    expected = {directory / name: content for name, content in render_files().items()}
    stale = sorted((set(directory.glob("*.mdx")) | set(directory.glob("*.json"))) - set(expected))
    changed = [path for path, content in expected.items() if not path.exists() or path.read_text() != content]
    if not check:
        directory.mkdir(parents=True, exist_ok=True)
        for path in changed:
            path.write_text(expected[path])
        for path in stale:
            path.unlink()
    return [str(path.relative_to(ROOT)) for path in changed + stale]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changes = build(check=args.check)
    if args.check and changes:
        parser.exit(
            1, "References are stale; run uv run python scripts/build_references.py:\n" + "\n".join(changes) + "\n"
        )
    print("Checked generated interface references." if args.check else "Generated interface references.")


if __name__ == "__main__":
    main()
